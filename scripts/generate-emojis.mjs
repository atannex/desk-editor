// Builds a compact emoji dataset (no CDN fallback images) from @tiptap/extension-emoji.
import { emojis } from "@tiptap/extension-emoji";
import fs from "fs";

const list = emojis
  .filter(
    (e) =>
      e.emoji &&
      e.group !== "components" &&
      !e.name.startsWith("regional_indicator") &&
      !e.name.includes("_tone"),
  )
  .map((e) => [
    e.emoji,
    e.shortcodes.join(" "),
    e.group || "smileys & emotion",
    (e.tags || []).join(" "),
  ]);

const js = `// Generated by scripts/generate-emojis.mjs — do not edit.\n// [emoji, shortcodes, group, tags]\nexport const emojiData = ${JSON.stringify(list)};\n\nexport const emojis = emojiData.map(([emoji, codes, group, tags]) => ({ emoji, shortcodes: codes.split(' '), name: codes.split(' ')[0], group, tags: tags ? tags.split(' ') : [] }));\n`;
fs.writeFileSync(
  new URL("../resources/js/data/emojis.js", import.meta.url),
  js,
);
console.log(`${list.length} emojis, ${(js.length / 1024).toFixed(0)} KB`);
